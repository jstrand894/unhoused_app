"""Open the app automatically when a logger is plugged in.

A tiny per-user launchd agent runs a shell loop that checks the USB bus every few seconds and opens the app on
the moment a logger appears (not while it stays plugged in, so closing the app is respected). Turn it off in
Settings. (launchd's own USB trigger was tried first: it re-launches its job every ~10 s for as long as the
device is present, which kept pulling the app to the front.)
"""
import os
import plistlib
import subprocess
import sys

LABEL = "com.jstrand.unhousedreader.usb"
PLIST = os.path.expanduser(f"~/Library/LaunchAgents/{LABEL}.plist")
SUPPORT = os.path.expanduser("~/Library/Application Support/Unhoused Reader Pro")
SCRIPT = os.path.join(SUPPORT, "watch_usb.sh")
INSTALLED = "/Applications/Unhoused Reader Pro.app"
POLL_SECONDS = 3

SCRIPT_TEXT = r'''#!/bin/sh
# Opens "$APP" when a HOBO logger is plugged in. Generated by the app; remove it with the Settings switch.
APP="$1"
was=0
while true; do
    if /usr/sbin/ioreg -p IOUSB -w0 | /usr/bin/grep -q "HOBO U23"; then now=1; else now=0; fi
    if [ "$now" = 1 ] && [ "$was" = 0 ]; then
        /usr/bin/pgrep -f "$APP/Contents/MacOS/" >/dev/null || /usr/bin/open -a "$APP"
    fi
    was=$now
    /bin/sleep __POLL__
done
'''.replace("__POLL__", str(POLL_SECONDS))


def app_path():
    """The .app to open: the running bundle, or the installed copy. None when running from source."""
    exe = os.path.realpath(sys.executable)
    marker = ".app/Contents/MacOS/"
    if getattr(sys, "frozen", False) and marker in exe:
        return exe.split(marker)[0] + ".app"
    return INSTALLED if os.path.isdir(INSTALLED) else None


def plist_for(app):
    return {"Label": LABEL, "ProgramArguments": ["/bin/sh", SCRIPT, app], "RunAtLoad": True, "KeepAlive": True,
            "ProcessType": "Background"}


def is_enabled() -> bool:
    return os.path.exists(PLIST)


def _launchctl(*args):
    return subprocess.run(["launchctl", *args], capture_output=True, text=True)


def enable():
    app = app_path()
    if not app:
        raise RuntimeError("Install the app in your Applications folder first.")
    os.makedirs(SUPPORT, exist_ok=True)
    with open(SCRIPT, "w") as f:
        f.write(SCRIPT_TEXT)
    os.chmod(SCRIPT, 0o755)
    plist = plist_for(app)
    os.makedirs(os.path.dirname(PLIST), exist_ok=True)
    with open(PLIST, "wb") as f:
        plistlib.dump(plist, f)
    domain = f"gui/{os.getuid()}"
    _launchctl("bootout", f"{domain}/{LABEL}")                # replace any older copy
    r = _launchctl("bootstrap", domain, PLIST)
    if r.returncode != 0:
        os.remove(PLIST)
        raise RuntimeError(f"Could not turn on auto-open: {r.stderr.strip() or r.stdout.strip()}")


def disable():
    _launchctl("bootout", f"gui/{os.getuid()}/{LABEL}")
    for path in (PLIST, SCRIPT):
        if os.path.exists(path):
            os.remove(path)
